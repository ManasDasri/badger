const FONT = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(' ')]));

const glyph = (ch) => FONT[ch] || FONT[ch.toUpperCase()] || FONT['?'];

// Width in font pixels (1px gap between glyphs).
export function pixelWidth(s) {
  let w = 0;
  for (const ch of s) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

// SVG path drawing `s` at (x, y) with pixel size p. Horizontal runs are merged.
export function pixelPath(s, x, y, p) {
  let d = '';
  const f = (n) => +n.toFixed(2);
  for (const ch of s) {
    const rows = glyph(ch);
    rows.forEach((row, ry) => {
      for (let cx = 0; cx < row.length;) {
        if (row[cx] !== '1') { cx++; continue; }
        let n = 1;
        while (row[cx + n] === '1') n++;
        d += `M${f(x + cx * p)} ${f(y + ry * p)}h${f(n * p)}v${f(p)}h${f(-n * p)}z`;
        cx += n;
      }
    });
    x += (rows[0].length + 1) * p;
  }
  return d;
}
